-- Что сломалось
-- -------------
-- Бейдж «Админ» на чужих анкетах берётся из публичной вьюхи
-- v_resident_reputation (обновление 29) — она единственная отдаёт
-- is_admin для НЕ своей строки, потому что RLS на user_profiles
-- показывает только собственную запись.
--
-- Но вьюха отдаёт голый is_admin, без исключения для владельца
-- проекта. Клиент отфильтровать его не может: e-mail во вьюхе нет
-- (и быть не должно — это публичные данные). Поэтому mr.hamzik1026@
-- начал показываться с бейджем «Админ» на карточках, хотя по замыслу
-- он выглядит обычным жителем.
--
-- Функция loadUsers() в lib/profiles/load.ts фильтр применяет, но она
-- работает со списком users в админ-панели, а не с витриной анкет —
-- отсюда и расхождение: в одном месте скрыт, в другом виден.
--
-- Как чиним
-- ---------
-- Прячем на уровне вьюхи: is_admin отдаётся как false для e-mail
-- владельца. Это единственное место, где решение работает для всех
-- клиентов сразу и не зависит от того, какой код читает витрину.
--
-- Список админов при этом не трогаем: права у владельца остаются
-- полными (их проверяет is_admin_email() и серверные роуты), скрывается
-- только ПОКАЗ бейджа.
--
-- Идемпотентно, можно перезапускать.
-- =============================================================================
set lock_timeout = '5s';

do $$
begin
  if not exists (select 1 from information_schema.tables
                 where table_schema = 'public' and table_name = 'user_profiles')
    then raise exception 'Нет таблицы user_profiles'; end if;
end $$;

-- ---------------------------------------------------------------------------
-- 1. Публичная витрина без бейджа у владельца проекта
--
-- e-mail в SELECT не выводим: вьюха публичная (grant для anon), и
-- почтовые адреса жителей наружу отдавать нельзя. Он используется
-- только в условии.
-- ---------------------------------------------------------------------------
drop view if exists public.v_resident_reputation;

create view public.v_resident_reputation
with (security_invoker = false)
as
select
  u.id,
  u.full_name,
  u.avatar_url,
  coalesce(u.resident_rating, 0)       as resident_rating,
  coalesce(u.resident_review_count, 0) as resident_review_count,
  coalesce(u.tasks_done_count, 0)      as tasks_done_count,
  greatest(0, extract(day from now() - u.created_at)::int) as account_days,
  -- Режим работы человека (обновление 26): применяется ко всем его
  -- анкетам специалиста. null / 'auto' — считать по расписанию.
  nullif(u.status_override, '')        as status_override,
  -- Признак администратора (обновление 29) с исключением для владельца
  -- проекта (обновление 44): он админ по правам, но житель по виду.
  case
    when lower(coalesce(u.email, '')) = 'mr.hamzik1026@gmail.com' then false
    else coalesce(u.is_admin, false)
  end                                  as is_admin
from public.user_profiles u;

grant select on public.v_resident_reputation to anon, authenticated;

comment on view public.v_resident_reputation is
  'Публичная репутация жителя. is_admin скрыт для владельца проекта: '
  'права у него остаются, бейдж «Админ» не показывается.';

