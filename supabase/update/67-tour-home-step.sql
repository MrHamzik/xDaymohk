-- 67. В гиде появился шаг «Главная страница» — нумерация сдвинулась
-- -----------------------------------------------------------------------------
-- WHAT CHANGED (решение владельца, 21.08.2026, ночь):
-- после шага с каталогом добавлен такой же шаг про ГЛАВНУЮ страницу
-- («нажмите Главная и пролистайте ленту»). Меню и всё после него
-- сдвинулись на один шаг вниз. Итого в гиде 13 шагов:
--
--   0  интро          5  виджет       10 реквизиты
--   1  язык           6  настройки    11 «Ваш профиль» (анкета)
--   2  каталог        7  уведомления  12 финал «Вот и всё» + «Завершить»
--   3  ГЛАВНАЯ (новый) 8 внешний вид
--   4  меню           9  «+»
--
-- Смещение для тех, кто уже в середине гида (tour_step хранит НОМЕР
-- шага): старые 3–9 (меню…реквизиты) становятся 4–10, анкета 10→11,
-- финал 11→12. Первые три шага не трогаем.
--
-- Идемпотентно: повторный запуск ничего не двигает (значения уже
-- в новых границах, условие between 3 and 9 после первого прогона
-- захватит уже сдвинутые… поэтому запускать РОВНО один раз).
-- =============================================================================

alter table public.user_settings
  drop constraint if exists user_settings_tour_step_range;

update public.user_settings
set tour_step = case
  when tour_step between 3 and 9 then tour_step + 1  -- меню…реквизиты
  when tour_step = 10 then 11                        -- анкета
  when tour_step = 11 then 12                        -- финал
  else tour_step                                     -- 0,1,2 и 12 без изменений
end;

alter table public.user_settings
  add constraint user_settings_tour_step_range
  check (tour_step >= 0 and tour_step <= 12);

comment on column public.user_settings.tour_step is
  'Номер шага единого гида из 13 (0-2 интро/язык/каталог, 3 главная, 4 меню, 5 виджет, 6 настройки, 7 уведомления, 8 внешний вид, 9 плюс, 10 реквизиты, 11 анкета, 12 финал). tour_done ставится только кнопкой «Завершить».';

