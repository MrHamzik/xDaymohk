-- =============================================================================
-- Даймохк — обновление 43
-- Настройка «Скрыть подсказки» в разделе «Задания».
--
-- Зачем
-- -----
-- В карточке задания много пояснений: как передаются деньги, что значит
-- «рассмотрение», как выбрать точку на карте. Первые разы они нужны, но
-- человеку, который взял двадцатое задание, они только мешают — он уже
-- всё знает, а текст занимает пол-экрана.
--
-- Что именно скрывается
-- ---------------------
-- ТОЛЬКО статичные памятки — те, что одинаковы у всех заданий.
-- НЕ скрываются:
--   • сообщения о состоянии («заявка отправлена», «условия изменились»,
--     «работа не принята») — это факты об этом задании;
--   • объяснения неактивных кнопок («исполнитель ещё не отметил
--     оплату») — без них интерфейс молча перестаёт работать.
--
-- Идемпотентно, можно перезапускать.
-- =============================================================================
set lock_timeout = '5s';

do $$
begin
  if not exists (select 1 from information_schema.tables
                 where table_schema = 'public' and table_name = 'user_settings')
    then raise exception 'Нет таблицы user_settings — сначала примените 28-user-settings.sql'; end if;
end $$;

-- ---------------------------------------------------------------------------
-- 1. Колонка настройки
--
-- default false: подсказки включены, пока человек их сам не выключит.
-- Новичок не должен остаться без объяснений.
-- ---------------------------------------------------------------------------
alter table public.user_settings
  add column if not exists hide_hints boolean not null default false;

comment on column public.user_settings.hide_hints is
  'Скрыть статичные подсказки в карточке задания. Сообщения о состоянии '
  'и причины неактивных кнопок скрытию не подлежат.';

-- ---------------------------------------------------------------------------
-- 2. Готово
-- ---------------------------------------------------------------------------
do $$
begin
  raise notice 'Обновление 43 применено: настройка «Скрыть подсказки» добавлена.';
end $$;
