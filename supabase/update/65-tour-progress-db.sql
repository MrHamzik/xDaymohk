-- =============================================================================
-- 65. Прогресс онбординга живёт в базе; анкета скрыта до завершения
-- -----------------------------------------------------------------------------
-- ТРЕБОВАНИЕ (от владельца, 21.08.2026).
--
-- Гид — это 11 шагов + два финальных окна: «Внешний вид» и «Заполнить
-- профиль». Пока всё это не пройдено:
--
--   · при каждом заходе гид открывается НА ТОМ этапе, где человек
--     остановился (закрыл браузер, зашёл с другого устройства — не важно);
--   · его личная анкета (personal-<uuid>) скрыта из каталога и карты.
--
-- Раньше номер шага лежал в sessionStorage и умирал вместе с вкладкой:
-- перезашёл — гид пропал, а человек остался зарегистрированным, и его
-- недозаполненная анкета «Житель Даймохк» висела в каталоге для всех.
--
-- Гость гид не проходит: у него нет аккаунта, нет строки в user_settings
-- и нет личной анкеты — правило его не касается.
--
-- СОСТАВ ОБНОВЛЕНИЯ.
--   1. user_settings.tour_step int 0..12
--        0–10 — шаг гида, 11 — «Внешний вид», 12 — «Заполнить профиль».
--        tour_done по-прежнему «пройдено всё»: он ставится приложением
--        ТОЛЬКО после отправки анкеты (finishOnboarding).
--   2. Дедушкин бэкфилл: существующим пользователям без строки
--      user_settings создаём строку с tour_done = true — все, кто
--      зарегистрировался до этого обновления, считаются прошедшими
--      (иначе их анкеты исчезли бы из каталога). Новые регистрации
--      строки сразу не имеют и идут по новому правилу.
--   3. RLS «profiles public read»: личная анкета видна другим только
--      при tour_done = true у владельца. Владелец видит свою анкету
--      всегда, админ — всегда.
--
-- Идемпотентно, можно перезапускать.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Колонка этапа
-- -----------------------------------------------------------------------------
alter table public.user_settings
  add column if not exists tour_step integer not null default 0;

comment on column public.user_settings.tour_step is
  'Этап онбординга: 0-10 шаги гида, 11 «Внешний вид», 12 «Заполнить профиль». tour_done ставится только после всех этапов.';

alter table public.user_settings
  drop constraint if exists user_settings_tour_step_range;
alter table public.user_settings
  add constraint user_settings_tour_step_range
  check (tour_step >= 0 and tour_step <= 12);

-- -----------------------------------------------------------------------------
-- 2. Дедушкин бэкфилл (ДО смены политики — чтобы ничья анкета не мигнула)
-- -----------------------------------------------------------------------------
-- Строки user_settings создаёт приложение при первой правке настроек.
-- Кто-то мог ни разу ничего не менять — строки нет. По новому правилу
-- «нет строки = онбординг не пройден = анкета скрыта», поэтому всех
-- СУЩЕСТВУЮЩИХ на момент обновления пользователей отмечаем прошедшими:
-- они регистрировались, когда гида-обязанности не было.
insert into public.user_settings (user_id, tour_done)
select up.id, true
from public.user_profiles up
where not exists (
  select 1 from public.user_settings us where us.user_id = up.id
)
on conflict (user_id) do nothing;

-- -----------------------------------------------------------------------------
-- 3. Личная анкета скрыта, пока онбординг не завершён
-- -----------------------------------------------------------------------------
-- Условие — подзапрос с EXISTS по первичному ключу user_settings
-- (user_id), поэтому поиск идёт по индексу и каталог не замедляется.
-- us.user_id и profiles.owner_id — оба uuid, сравнение без приведения,
-- иначе Postgres не использовал бы индекс.
--
-- Заменяем политику целиком (drop + create): ALTER POLICY не умеет
-- править тело USING. Владелец и админ видят анкету на любом этапе —
-- человек должен видеть, что о нём уже известно.
--
-- ВАЖНО: политика ссылается на user_settings, которая создаётся
-- обновлением 28. Свежая установка: сначала schema.sql, затем обновления
-- по порядку (так описано и в supabase/README.md).
drop policy if exists "profiles public read" on public.profiles;
create policy "profiles public read"
  on public.profiles for select
  using (
    (
      not (is_hidden or is_banned)
      and not (
        is_personal
        and not exists (
          select 1
          from public.user_settings us
          where us.user_id = profiles.owner_id
            and us.tour_done = true
        )
      )
    )
    or auth.uid() = owner_id
    or is_admin_email()
  );

