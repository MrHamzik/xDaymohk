-- 55-welcome-once.sql
-- Приветственное уведомление — строго один раз на аккаунт.
--
-- Что было не так. Признак «приветствие отправлено» жил только в
-- localStorage браузера, под одним общим ключом daymohk-onboarded-v1:
--   * зашёл с телефона после компьютера — письмо пришло снова;
--   * почистил кэш или открыл в приватном окне — снова;
--   * на общем компьютере ключ от прошлого человека мешал новому.
-- Признак, привязанный к человеку, обязан лежать на сервере.
--
-- Колонка ставится один раз и больше не снимается. Проверять её надо
-- ДО отправки: если true — уведомление не создаётся.

alter table public.user_settings
  add column if not exists welcome_sent boolean not null default false;

comment on column public.user_settings.welcome_sent is
  'Приветственное уведомление уже отправлено. Ставится один раз, не сбрасывается.';

-- Тем, кто зарегистрировался до этого обновления, приветствие уже
-- приходило — помечаем, иначе они получат его повторно.
update public.user_settings
set welcome_sent = true
where welcome_sent = false;
