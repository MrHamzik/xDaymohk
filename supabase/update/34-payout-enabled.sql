-- =============================================================================
-- Даймохк — обновление 34
-- Переключатель «принимаю безналичные переводы» в реквизитах.
--
-- Зачем колонка, а не просто сворачивание блока в интерфейсе
-- ----------------------------------------------------------
-- Тумблер выключает не только форму, но и САМУ ВЫДАЧУ реквизитов
-- заказчику. Человек мог заполнить номер карты, потом передумать —
-- и его данные не должны продолжать показываться другим только потому,
-- что строка в таблице осталась. Значит, решение принимает сервер, а
-- не клиент, и флаг обязан жить в БД.
--
-- default false: реквизиты не начинают показываться сами по себе у тех,
-- кто уже заполнил их до этого обновления. Показать чужой номер карты
-- без явного согласия — хуже, чем попросить включить тумблер заново.
--
-- Идемпотентно, можно перезапускать.
-- =============================================================================
set lock_timeout = '5s';

do $$
begin
  if not exists (select 1 from information_schema.tables
                 where table_schema = 'public' and table_name = 'payout_methods')
    then raise exception 'Нет таблицы payout_methods — сначала примените 33-payout-methods.sql'; end if;
end $$;

alter table public.payout_methods
  add column if not exists is_enabled boolean not null default false;

comment on column public.payout_methods.is_enabled is
  'Согласие показывать реквизиты заказчику. Выключено — сервер отдаёт '
  'пустые реквизиты, даже если строка заполнена.';

-- Тем, кто УЖЕ заполнил реквизиты до этого обновления, включаем флаг:
-- они это сделали осознанно, и молча перестать показывать их значило бы
-- сломать работающие сделки. Пустые строки остаются выключенными.
update public.payout_methods
set is_enabled = true
where is_enabled = false
  and (
    coalesce(sbp_phone, '') <> ''
    or coalesce(card_number, '') <> ''
    or coalesce(yoomoney_wallet, '') <> ''
  );

do $$
begin
  raise notice 'Обновление 34 применено: payout_methods.is_enabled готова.';
end $$;
