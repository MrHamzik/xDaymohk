-- =============================================================================
-- 63. «Уведомления» больше не скрыты в боковом меню (п.12)
-- -----------------------------------------------------------------------------
-- ПРОБЛЕМА.
--
-- В настройках по умолчанию пункт «Уведомления» шёл СКРЫТЫМ:
-- hiddenMenu = ['notify'] (lib/settings/defaults.ts). В обычном режиме
-- боковое меню его не рисует, а в режиме правки он виден с закрытым
-- глазиком — человек видит пункт, который «есть, но пропадает», и не
-- понимает, кто его спрятал.
--
-- В коде значение по умолчанию уже исправлено на пустой список. Но у
-- всех, кто хоть раз сохранял настройки, в базе лежит своя строка со
-- значением {notify}, и её умолчание не перекрывает: сервер каждый раз
-- присылает старый список обратно.
--
-- РЕШЕНИЕ.
--
-- Разово убрать 'notify' из user_settings.hidden_menu у всех строк, где
-- он там оказался.
--
-- Осознанно затрагиваем и тех, кто спрятал пункт вручную: отличить
-- «спрятал сам» от «досталось от умолчания» в данных невозможно —
-- значение одно и то же. Цена ошибки несимметрична: лишний видимый
-- пункт человек уберёт одним нажатием в режиме правки, а пропавший
-- раздел он ищет в поддержке.
--
-- Остальные скрытые пункты не трогаем: их выбирали руками.
--
-- Запуск повторно безопасен: второй раз условие уже никого не найдёт.
-- =============================================================================

-- hidden_menu — jsonb-массив строк (миграция 51), поэтому убираем
-- элемент через разбор и пересборку, а не array_remove.
update public.user_settings
set hidden_menu = coalesce(
      (
        select jsonb_agg(item)
        from jsonb_array_elements_text(hidden_menu) as item
        where item <> 'notify'
      ),
      '[]'::jsonb
    )
where jsonb_typeof(hidden_menu) = 'array'
  and hidden_menu ? 'notify';

