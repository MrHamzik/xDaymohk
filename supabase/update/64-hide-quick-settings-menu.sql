-- =============================================================================
-- 64. Быстрые настройки в меню скрыты по умолчанию (п.12)
-- -----------------------------------------------------------------------------
-- ПРОБЛЕМА.
--
-- В разделе «Дополнительно» бокового меню появились четыре строки:
-- «Уведомления», «Язык», «Режим работы», «Тема оформления». Те же
-- четыре переключателя уже стоят плиткой в шапке меню, поэтому строками
-- они нужны не всем — по замыслу их видно только тем, кто включит их
-- глазиком в лайт-режиме.
--
-- В коде умолчание уже такое:
--
--   hiddenMenu: ['notify', 'lang', 'status', 'theme']   (lib/settings/defaults.ts)
--
-- Но умолчание применяется только к тем, у кого строки в user_settings
-- ещё нет. У всех остальных в базе лежит свой список — чаще всего
-- пустой (его же оставила миграция 63, убиравшая оттуда 'notify').
-- Сервер присылает этот список обратно, и три новых пункта показываются
-- всем без спроса.
--
-- РЕШЕНИЕ.
--
-- Разово дописать недостающие идентификаторы в user_settings.hidden_menu.
--
-- Ничего не удаляем: пункты, скрытые человеком вручную, остаются
-- скрытыми. Дописываем только те четыре, которых в списке ещё нет, —
-- поэтому повторный запуск ничего не меняет.
--
-- Обратная совместимость с миграцией 63: она убирала 'notify' из
-- списка, эта возвращает его обратно уже осознанно — вместе с тремя
-- соседями и с плиткой в шапке, которой на момент 63 у пункта не было.
-- =============================================================================

-- hidden_menu — jsonb-массив строк (миграция 51). Собираем объединение
-- старого списка и четвёрки, дубликаты убирает distinct.
update public.user_settings
set hidden_menu = coalesce(
      (
        select jsonb_agg(distinct item)
        from (
          select jsonb_array_elements_text(hidden_menu) as item
          union
          select unnest(array['notify', 'lang', 'status', 'theme']) as item
        ) as merged
      ),
      '[]'::jsonb
    )
where jsonb_typeof(hidden_menu) = 'array'
  and not (
    hidden_menu ? 'notify'
    and hidden_menu ? 'lang'
    and hidden_menu ? 'status'
    and hidden_menu ? 'theme'
  );

