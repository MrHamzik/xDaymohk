-- Даймохк — обновление 45
-- Свой звук для каждой группы уведомлений.
--
-- Зачем
-- -----
-- Раньше все уведомления звучали одинаково: тумблер «Звук» только
-- включал общий сигнал. По звуку нельзя было понять, пришло задание,
-- ответ поддержки или жалоба — приходилось доставать телефон.
--
-- Теперь у каждой группы свой сигнал, выбирается в настройках.
--
-- Где хранится
-- ------------
-- Внутри существующей колонки notification_prefs (jsonb): она уже
-- хранит по группе { show, sound }, добавляется поле soundId. Отдельная
-- колонка не нужна — это настройка той же самой группы.
--
-- Схему менять не требуется: jsonb принимает новое поле как есть.
-- Файл нужен как отметка в истории обновлений и место для проверки.
--
-- Значения soundId — закрытый список (см. lib/notification-sounds.ts):
--   none, chime, ding, double, soft, alert, drop
-- Клиент отбрасывает всё, чего нет в списке, поэтому мусор из БД в
-- проигрыватель не попадёт.
--
-- Идемпотентно, можно перезапускать.
-- =============================================================================
set lock_timeout = '5s';

do $$
begin
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'user_settings'
                   and column_name = 'notification_prefs')
    then raise exception 'Нет колонки user_settings.notification_prefs — примените 28-user-settings.sql'; end if;
end $$;

comment on column public.user_settings.notification_prefs is
  'Настройки по группам уведомлений: { "tasks": { "show": true, '
  '"sound": true, "soundId": "chime" } }. soundId — из закрытого списка '
  'в lib/notification-sounds.ts; пусто — звук группы по умолчанию.';

do $$
begin
  raise notice 'Обновление 45 применено: soundId в notification_prefs задокументирован.';
end $$;

