-- ============================================================================
-- 11-pgcron-letters.sql
-- Автоматическая доставка запланированных писем через pg_cron.
--
-- Достаточно ОДНОГО из двух способов:
--   A) pg_cron (этот файл) — доставка прямо из БД каждые 5 минут;
--   B) Vercel Cron — vercel.json + app/api/cron/letters (+ CRON_SECRET).
-- Можно включить оба (pg_cron надёжнее, Vercel — запасной).
--
-- Применение: вставьте в Supabase SQL Editor и нажмите Run.
-- ============================================================================

-- pg_cron в Supabase включён по умолчанию (схема cron).
-- Ставим задачу каждые 5 минут.
select cron.schedule(
  'letters-delivery',           -- имя задачи
  '*/5 * * * *',                -- каждые 5 минут
  'select public.process_letter_schedule();'
);

