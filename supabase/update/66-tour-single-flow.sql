-- 66. Единый гид из 12 шагов + умолчания «включено»
-- -----------------------------------------------------------------------------
-- ИЗМЕНЕНИЯ ПОВЕДЕНИЯ (решение владельца, 21.08.2026).
--
-- 1. Гид стал одним целым: анкета и финальное окно «Вот и всё» — это
--    шаги 11 и 12 гида, а не отдельные модалки после него. Значения
--    tour_step теперь означают НОМЕР ШАГА:
--
--      0–9  — обычные шаги (язык, каталог, меню, виджет, настройки,
--             уведомления, внешний вид, «+», реквизиты);
--      10   — «Ваш профиль» (заполнение анкеты);
--      11   — финал с кнопкой «Завершить» (только она ставит tour_done).
--
--    Старая схема (11 — «Внешний вид», 12 — «Анкета») умерла; значения
--    11 и 12 от неё зажимаются в 11 — человек доедет финал и завершит.
--
-- 2. «Автоактивация статуса Темщика» включена по умолчанию для ВСЕХ:
--    открывший раздел «Аренца Темщик» сразу виден в списке исполнителей.
--    Отключившие вручную отключат снова — различить «не трогал» и
--    «отключил» в базе нельзя, старое умолчание было false.
--
-- Звук уведомлений включён по умолчанию в ПРИЛОЖЕНИИ (notification_prefs
-- пуст = всё включено), базу для этого менять не нужно.
--
-- Идемпотентно, можно перезапускать.
-- =============================================================================

-- 1. Границы этапа: 0..11 (номер шага единого гида).
alter table public.user_settings
  drop constraint if exists user_settings_tour_step_range;

update public.user_settings
set tour_step = 11
where tour_step > 11;

alter table public.user_settings
  add constraint user_settings_tour_step_range
  check (tour_step >= 0 and tour_step <= 11);

comment on column public.user_settings.tour_step is
  'Номер шага единого гида (0-9 обычные, 10 анкета, 11 финал). tour_done ставится только кнопкой «Завершить».';

-- 2. Автоактивация Темщика — включена всем.
update public.user_settings
set auto_active_on_open = true
where auto_active_on_open = false;

