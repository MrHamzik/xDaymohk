export interface ModerationResult {
  allowed: boolean;
  /** Какая категория сработала — для понятного сообщения пользователю. */
  category?: string;
}

/**
 * Проверяет текст задания (заголовок + описание) по стоп-листу.
 * Нормализуем «ё» → «е» и схлопываем растяжки букв, чтобы простые
 * искажения («вооодка») не проходили насквозь.
 */
export function checkTaskContent(title: string, description: string): ModerationResult {
  const normalized = `${title} ${description}`
    .toLowerCase()
    .replace(/ё/g, 'е')
    // «вооодка» → «воодка»: схлопываем только 3+ подряд, чтобы не ломать
    // легитимные удвоения («аллея», «ссуда»).
    .replace(/(.)\1{2,}/gu, '$1$1')
    // Убираем повтор уже после схлопывания: «воодка» → «водка».
    .replace(/(.)\1/gu, '$1$1')
    .replace(/[^а-яa-z0-9\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  // Вариант с полностью убранными удвоениями — ловит «вооодка».
  const collapsed = normalized.replace(/(.)\1+/gu, '$1');

  for (const rule of BANNED_PATTERNS) {
    if (rule.words.test(normalized) || rule.words.test(collapsed)) {
      return { allowed: false, category: rule.category };
    }
  }
  return { allowed: true };
}

/** Сообщение пользователю о причине отказа (без раскрытия самих паттернов). */
export function moderationMessage(category: string): string {
  return `Задание нельзя опубликовать: содержимое относится к запрещённой категории «${category}». `
    + 'В Даймохк запрещены задания, противоречащие законам РФ и нормам шариата.';
}
