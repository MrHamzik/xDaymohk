/**
 * Стоп-лист для заданий «Аренца Темщик» / «ГIончалла».
 *
 * Проверка автоматическая, на публикации: полная премодерация задержала бы
 * срочные задания («купить лекарство сейчас»), поэтому ловим очевидное по
 * ключевым словам, а спорное разбирают админы по жалобам.
 *
 * ВАЖНО про границы слов: в JS `\w` — это [A-Za-z0-9_], кириллицу он НЕ
 * покрывает, поэтому `\b` рядом с русским словом не срабатывает и правило
 * молча перестаёт ловить (проверено тестом: /\bводк\w*\b/iu не находит
 * «водки»). Поэтому вместо \b и \w используем явные классы кириллицы и
 * lookaround-границы RU_START / RU_END.
 *
 * Это фильтр, а не гарантия: изощрённый обход возможен — страхует кнопка
 * «Пожаловаться» и разбор администрацией.
 */

/** Символы, из которых состоит «слово» (кириллица + латиница + цифры). */
const WORD_CHARS = 'а-яёa-z0-9';
/** Граница слева: перед словом нет буквы/цифры. */
const RU_START = `(?<![${WORD_CHARS}])`;
/** Граница справа: после слова нет буквы/цифры. */
const RU_END = `(?![${WORD_CHARS}])`;
/** Хвост словоформы: любое окончание из кириллицы. */
const TAIL = '[а-яё]*';

/** Собирает regexp из списка основ с корректными границами. */
function buildPattern(stems: string[]): RegExp {
  const body = stems.map((stem) => `${RU_START}${stem}${RU_END}`).join('|');
  return new RegExp(body, 'iu');
}

