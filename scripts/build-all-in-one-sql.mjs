#!/usr/bin/env node
/**
 * Build the bundled all-in-one.sql from the per-step files in
 * supabase/steps/. Re-run after editing any step file.
 *
 *   node scripts/build-all-in-one-sql.mjs
 *
 * Output: supabase/all-in-one.sql
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const STEPS_DIR = resolve(__dirname, '..', 'supabase', 'steps');
const OUT_FILE = resolve(__dirname, '..', 'supabase', 'all-in-one.sql');

const HEADER = `-- =============================================================================
-- all-in-one.sql (auto-generated by scripts/build-all-in-one-sql.mjs)
-- Bundles supabase/steps/01..08 into a single SQL file for one-shot deploy.
-- After editing any step file, run \`node scripts/build-all-in-one-sql.mjs\`
-- and paste the regenerated file into Supabase SQL Editor.
-- =============================================================================

`;

const stepFiles = readdirSync(STEPS_DIR)
  .filter((f) => /^\d+.*\.sql$/.test(f))
  .sort();

let bundle = HEADER;
for (const file of stepFiles) {
  const path = join(STEPS_DIR, file);
  const content = readFileSync(path, 'utf8');
  bundle += `-- >>>>>> ${file} (${(statSync(path).size / 1024).toFixed(1)} kB) >>>>>>\n`;
  bundle += content;
  if (!content.endsWith('\n')) bundle += '\n';
  bundle += `-- <<<<<< ${file} <<<<<<\n\n`;
}

writeFileSync(OUT_FILE, bundle);
console.log(`Wrote ${OUT_FILE} (${(statSync(OUT_FILE).size / 1024).toFixed(1)} kB, ${stepFiles.length} steps)`);
